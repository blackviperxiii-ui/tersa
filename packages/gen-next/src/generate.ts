import { extractSlots, injectSlots, slotBegin, slotEnd, withGeneratedBanner } from "./slots";

export interface GeneratedFile {
  path: string;
  content: string;
}

export interface GenerateOptions {
  /** package.json name of the emitted app. Defaults to a slug of the app name. */
  packageName?: string;
  /** When set, preserved @tersa-slot regions are read from existing files in this directory. */
  existingDir?: string;
}

/** Exact versions the generated app is built and tested against. */
