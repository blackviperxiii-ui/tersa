const STATIC_DIR = fileURLToPath(new URL("../templates/static/", import.meta.url));

function readStatic(): GeneratedFile[] {
  const out: GeneratedFile[] = [];
  const visit = (dir: string, rel: string) => {
    for (const name of readdirSync(dir).sort()) {
      const full = path.join(dir, name);
      const relPath = rel ? `${rel}/${name}` : name;
      if (statSync(full).isDirectory()) visit(full, relPath);
      else
        out.push({
          path: relPath === "gitignore" ? ".gitignore" : relPath,
          content: readFileSync(full, "utf8"),
        });
    }
  };
  visit(STATIC_DIR, "");
  return out;
}

export function slugify(name: string) {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "tersa-app"
  );
}

function readExistingSlots(existingDir: string | undefined, rel: string): Map<string, string> {
  if (!existingDir) return new Map();
  const full = path.join(existingDir, rel);
  if (!existsSync(full)) return new Map();
  return extractSlots(readFileSync(full, "utf8"));
}

function dataSource(app: AppNode, preserved: Map<string, string>): string {
  const plan = planData(app);
  const parts: string[] = [
    withGeneratedBanner(""),
    "// Mock data generated by tersa. Extend in the custom slot or replace with real fetching.",
    "",
  ];
  const needsRow = plan.lists.some((l) => !l.uses.some((u) => u.kind === "kpis"));
  const needsKpi = plan.lists.some((l) => l.uses.some((u) => u.kind === "kpis"));
  const typeImports = [
    needsKpi ? "type KpiItem" : "",
    needsRow ? "type Row" : "",
    needsKpi ? "kpi" : "",
  ].filter(Boolean);
  if (typeImports.length)
    parts.push(`import { ${typeImports.sort().join(", ")} } from "@/lib/types";`, "");
  for (const l of plan.lists) parts.push(listSource(l, listLength(l)), "");
  for (const r of plan.records) parts.push(recordSource(r), "");
  for (const i of plan.items) parts.push(itemSource(i), "");
  parts.push(
    slotBegin("custom"),
    "// Add exports that should survive `tersa gen` (helpers, fixtures, manual overrides).",
    slotEnd("custom"),
  );
  return injectSlots(parts.join("\n"), preserved);
}

function apiSource(app: AppNode, preserved: Map<string, string>): string {
  const plan = planData(app);
  const fns = [...plan.apiFns.entries()].map(([name, info]) => {
    const params =
      info.kind === "row"
        ? info.args.map((a) => `${a}: unknown`).join(", ")
        : info.kind === "form"
          ? "values: Record<string, unknown>"
          : "";
    const log =
      info.kind === "row"
        ? `{ ${info.args.join(", ")} }`
        : info.kind === "form"
          ? "values"
          : '"clicked"';
    return `  async ${name}(${params}) {
    await delay();
    console.info("api.${name}", ${log});
  },`;
  });
  const body = `${withGeneratedBanner("")}// Action handlers referenced by the spec. Wire stubs to real endpoints.
type ApiFn = (...args: never[]) => Promise<unknown>;

const delay = (ms = 400) => new Promise((resolve) => setTimeout(resolve, ms));

export const api: Record<string, ((...args: any[]) => Promise<unknown>) | undefined> = {
${fns.join("\n")}
};

export type { ApiFn };

${slotBegin("custom")}// Handlers not in app.tsa, or overrides that should survive regeneration.
${slotEnd("custom")}
`;
  return injectSlots(body, preserved);
}

export function generate(app: AppNode, options: GenerateOptions = {}): GeneratedFile[] {
  const existingDir = options.existingDir;
  const dataSlots = readExistingSlots(existingDir, "lib/data.ts");
  const apiSlots = readExistingSlots(existingDir, "lib/api.ts");
  const stubSlots = readExistingSlots(existingDir, "lib/stubs.ts");

  const files: GeneratedFile[] = [...readStatic()];
  const pages = app.children.filter((c): c is PageNode => c.type === "page");

  files.push({
    path: "package.json",
    content: `${JSON.stringify(
      {
        name: options.packageName ?? slugify(app.name),
        private: true,
        version: "0.1.0",
        scripts: {
          dev: "next dev",
          build: "next build",
          start: "next start",
          typecheck: "tsc --noEmit",
        },
        ...APP_DEPENDENCIES,
      },
      null,
      2,
    )}\n`,
  });
  files.push({ path: "app/globals.css", content: globalsCss(themeCss(app.theme)) });
  files.push({ path: "app/layout.tsx", content: layoutSource(app) });
  const root = rootPageSource(app);
  if (root) files.push({ path: "app/page.tsx", content: root });
  for (const page of pages) {
    const dir = page.path === "/" ? "app" : `app${page.path}`;
    files.push({ path: `${dir}/page.tsx`, content: pageSource(page) });
    files.push({ path: `${dir}/loading.tsx`, content: loadingSource(page) });
  }
  files.push({ path: "lib/data.ts", content: dataSource(app, dataSlots) });
  files.push({ path: "lib/api.ts", content: apiSource(app, apiSlots) });
  files.push({
    path: "lib/stubs.ts",
    content: injectSlots(withGeneratedBanner(stubsSource(app)), stubSlots),
  });
  files.push({
    path: "README.md",
    content: `# ${app.name}

Generated by [tersa](https://github.com/blackviperxiii-ui/tersa). Next.js App Router, Tailwind v4, shadcn-style components, \`${app.theme}\` theme.

\`\`\`sh
pnpm install
pnpm dev
\`\`\`

- Pages: ${pages.map((p) => `\`${p.path}\``).join(", ")}
- Mock data in \`lib/data.ts\`; action stubs in \`lib/api.ts\`; fetch placeholders in \`lib/stubs.ts\`.
- Protected slots: edit between \`@tersa-slot begin custom\` markers in \`lib/data.ts\` / \`lib/api.ts\`.
- Colors come from CSS variables in \`app/globals.css\`. Use the token utilities (\`bg-primary\`, \`text-muted-foreground\`) instead of raw values.
`,
  });
  return files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}
