// Builds DTCG tokens into CSS variables + a Tailwind v4 @theme block using Style Dictionary.
// Output: src/generated/<theme>.ts (bundled into the package) and css/<theme>.css.
import StyleDictionary from "style-dictionary";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const themes = ["aurora"];

// Token path -> CSS variable name: color.primary-foreground -> primary-foreground,
// radius.base -> radius, font.body -> font-body. Values pass through untouched (OKLCH stays OKLCH).
StyleDictionary.registerTransform({
  name: "tersa/name",
  type: "name",
  transform: (token) => {
    const parts = token.path[0] === "color" ? token.path.slice(1) : token.path;
    return parts.filter((p, i) => !(p === "base" && i === parts.length - 1)).join("-");
  },
});

StyleDictionary.registerFormat({
  name: "tersa/css-vars",
  format: ({ dictionary, options }) => {
    const lines = dictionary.allTokens.map((t) => `  --${t.name}: ${t.$value ?? t.value};`);
    return `${options.selector} {\n${lines.join("\n")}\n}\n`;
  },
});

StyleDictionary.registerFormat({
  name: "tersa/tailwind-theme",
  format: ({ dictionary }) => {
    const colors = dictionary.allTokens.filter((t) => t.path[0] === "color");
    const lines = colors.map((t) => `  --color-${t.name}: var(--${t.name});`);
    lines.push(
      "  --radius-sm: calc(var(--radius) - 4px);",
      "  --radius-md: calc(var(--radius) - 2px);",
      "  --radius-lg: var(--radius);",
      "  --radius-xl: calc(var(--radius) + 4px);",
    );
    return `@theme inline {\n${lines.join("\n")}\n}\n`;
  },
});

async function render(file, format, selector) {
  const sd = new StyleDictionary({
    log: { verbosity: "silent" },
    source: [path.join(root, "tokens", file)],
    platforms: {
      css: {
        transforms: ["tersa/name"],
        files: [{ destination: "out.css", format, options: { selector } }],
      },
    },
  });
  await sd.hasInitialized;
  const [out] = await sd.formatPlatform("css");
  return out.output;
}

for (const name of themes) {
  const light = await render(`${name}.json`, "tersa/css-vars", ":root");
  const dark = await render(`${name}.dark.json`, "tersa/css-vars", ".dark");
  const tailwind = await render(`${name}.json`, "tersa/tailwind-theme", "");
  const names = [...light.matchAll(/^\s+--([\w-]+):/gm)].map((m) => m[1]);

  await mkdir(path.join(root, "src", "generated"), { recursive: true });
  await mkdir(path.join(root, "css"), { recursive: true });

  const ts = [
    "// Generated by scripts/build.mjs. Do not edit.",
    `export const ${name}Vars = ${JSON.stringify(light + "\n" + dark)};`,
    `export const ${name}Tailwind = ${JSON.stringify(tailwind)};`,
    `export const ${name}TokenNames: string[] = ${JSON.stringify(names)};`,
    "",
  ].join("\n");
  await writeFile(path.join(root, "src", "generated", `${name}.ts`), ts);
  await writeFile(path.join(root, "css", `${name}.css`), `${light}\n${dark}\n${tailwind}`);
}
console.log(`themes: built ${themes.join(", ")}`);
